export function isValidReactionEmoji(emoji) {
  if (!emoji || typeof emoji !== "string") return false;
  const value = emoji.trim();
  if (!value || value.length > 16) return false;
  if (MESSAGE_REACTIONS.includes(value) || QUICK_REACTIONS.includes(value)) {
    return true;
  }
  // Allow most emoji sequences; block plain long ASCII text
  if (/^[a-zA-Z0-9\s.,!?]{2,}$/.test(value)) return false;
  return /[^\u0000-\u007F]/.test(value);
}

export function summarizeReactions(reactions = [], currentUserId = "") {
  const map = new Map();

  reactions.forEach((reaction) => {
    if (!reaction?.emoji) return;
    const key = reaction.emoji;
    if (!map.has(key)) {
      map.set(key, { emoji: key, count: 0, reactedByMe: false });
    }
    const entry = map.get(key);
    entry.count += 1;
    if (String(reaction.userId) === String(currentUserId)) {
      entry.reactedByMe = true;
    }
  });

  return Array.from(map.values());
}

const RECENT_KEY = "quickchat_recent_reactions";

export function getRecentReactions(limit = 16) {
  try {
    const raw = JSON.parse(localStorage.getItem(RECENT_KEY) || "[]");
    if (!Array.isArray(raw)) return QUICK_REACTIONS.slice(0, limit);
    return raw.filter(Boolean).slice(0, limit);
  } catch {
    return QUICK_REACTIONS.slice(0, limit);
  }
}

export function pushRecentReaction(emoji) {
  if (!emoji) return;
  try {
    const prev = getRecentReactions(40).filter((item) => item !== emoji);
    const next = [emoji, ...prev].slice(0, 40);
    localStorage.setItem(RECENT_KEY, JSON.stringify(next));
  } catch {
    // ignore storage errors
  }
}
